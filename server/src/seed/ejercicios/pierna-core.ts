// Dos criterios que gobiernan este bloque:
//
// 1. Isquiotibiales: tres de las cuatro porciones cruzan cadera Y rodilla, así
//    que su longitud depende de ambas. El curl sentado (cadera flexionada) las
//    trabaja alargadas y el tumbado no — por eso se modelan como variantes con
//    distinta grilla. En cambio la posición del TOBILLO no se modela: en un RCT
//    de 10 semanas no afectó ni activación ni hipertrofia (Cadeo et al. 2023,
//    PubMed 10.1080/17461391.2023.2214794).
//
// 2. Carga axial: marca los ejercicios que comprimen la columna. Es lo que
//    separa a la sentadilla de la prensa aunque ambas sean rodilla-dominante, y
//    lo que le permite al coach bajar fatiga sistémica sin cambiar de patrón.

